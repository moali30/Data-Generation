"""
semsim.ui.pages.complexity
==========================
Stage 2 -- Complex Realities Simulation.

A perfectly clean measurement model never happens outside a textbook.  This
page is where the researcher deliberately dirties the data in the three ways
real questionnaires are dirty:

*   **Cross-loadings** -- one item tapping more than one construct, either
    listed explicitly or generated by a policy.
*   **Error covariances** -- residuals that correlate because two items are
    worded alike, with the theoretical reason recorded for the write-up.
*   **A common method factor** -- the single-source bias of self-report data.

Every one of those is an extra estimated parameter, so the page ends with a
live strip showing what the complications cost in degrees of freedom.  A
researcher who cannot see that price pays it without noticing.
"""

from __future__ import annotations

from typing import List, Tuple

from PySide6.QtWidgets import (
    QCheckBox, QFrame, QHBoxLayout, QLineEdit, QScrollArea, QVBoxLayout,
    QWidget,
)

from semsim.core.spec import CrossLoading, ErrorCovariance
from semsim.ui import theme
from semsim.ui.i18n import translator
from semsim.ui.pages.base import (
    IdCombo, Row, RowList, StagePage, factor_choices, item_choices,
)
from semsim.ui.widgets.common import (
    Collapsible, Field, InfoBanner, StatBadge, TCheckBox, TKey,
    ValueSlider, float_spin, int_spin, percent_spin, percent_value,
)

#: Ranges the stage works in.  Anything larger stops being "a complication"
#: and becomes a different measurement model.
CROSS_LOADING_RANGE = (-0.60, 0.60)
ERROR_COV_RANGE = (-0.90, 0.90)
METHOD_LOADING_RANGE = (0.0, 0.70)


def _clear_error(field: Field) -> None:
    """Clear a field's error without leaving the red text behind.

    ``Field.set_error("")`` restores the role and the label but leaves the old
    message visible when the field has no standing hint, so the hint key is
    cleared too -- which hides it.
    """
    field.set_error("")
    field.set_hint_key("")


class ComplexityPage(StagePage):
    TITLE_KEY = "stage.2.title"
    SUBTITLE_KEY = "stage.2.subtitle"

    # ------------------------------------------------------------------ #
    # Construction
    # ------------------------------------------------------------------ #

    def build(self) -> None:
        self._build_cross_loadings()
        self._build_error_covariances()
        self._build_method_factor()
        self._build_summary()
        self.scroll.add_stretch()

        # Derived numbers follow every value edit, not just structural ones.
        self.state.spec_changed.connect(self._update_summary)
        self.rebuild()

    # -- section 1: cross-loadings ------------------------------------- #

    def _build_cross_loadings(self) -> None:
        card = self.add_card("x.cross_loadings")
        card.add(InfoBanner("x.cross_loadings.explain"))

        self.cross_rows = RowList("x.add_cross_loading",
                                  empty_key="x.cross_loadings.empty")
        self.cross_rows.add_button.clicked.connect(self._add_cross_loading)
        card.add(self.cross_rows)
        self._cross_hint = TKey("x.needs_items", role="hint")
        card.add(self._cross_hint)

        policy = Collapsible("x.auto_policy")
        card.add(policy)
        self._policy_enabled = TCheckBox("x.auto_enable")
        self._policy_enabled.toggled.connect(self._on_policy_enabled)
        policy.add(self._policy_enabled)

        self._policy_proportion = percent_spin(0.20)
        self._policy_proportion.valueChanged.connect(lambda _v: self._on_policy())
        self._policy_fields: List[Field] = []
        self._policy_fields.append(policy.add(
            Field("x.proportion_items", self._policy_proportion)))

        host = QWidget()
        host_lay = QHBoxLayout(host)
        host_lay.setContentsMargins(0, 0, 0, 0)
        host_lay.setSpacing(6)
        self._magnitude_low = float_spin(0.0, CROSS_LOADING_RANGE[1], 0.10,
                                         decimals=2, step=0.05)
        self._magnitude_high = float_spin(0.0, CROSS_LOADING_RANGE[1], 0.25,
                                          decimals=2, step=0.05)
        host_lay.addWidget(TKey("r.min", role="hint"))
        host_lay.addWidget(self._magnitude_low)
        host_lay.addWidget(TKey("r.max", role="hint"))
        host_lay.addWidget(self._magnitude_high)
        host_lay.addStretch(1)
        self._magnitude_low.valueChanged.connect(lambda _v: self._on_magnitude())
        self._magnitude_high.valueChanged.connect(lambda _v: self._on_magnitude())
        self._policy_fields.append(policy.add(
            Field("x.magnitude_range", host,
                  hint_key="x.magnitude_range.hint")))

        self._policy_across = TCheckBox("x.across_only")
        self._policy_across.toggled.connect(lambda _c: self._on_policy())
        policy.add(self._policy_across)
        self._policy_negative = TCheckBox("x.allow_negative")
        self._policy_negative.toggled.connect(lambda _c: self._on_policy())
        policy.add(self._policy_negative)
        self._policy_switches = [self._policy_across, self._policy_negative]

        self._policy_max = int_spin(1, 8, 1)
        self._policy_max.valueChanged.connect(lambda _v: self._on_policy())
        self._policy_fields.append(policy.add(
            Field("x.max_per_item", self._policy_max)))

    # -- section 2: error covariances ---------------------------------- #

    def _build_error_covariances(self) -> None:
        card = self.add_card("x.error_cov")
        card.add(InfoBanner("x.error_cov.explain"))

        self.error_rows = RowList("x.add_error_cov",
                                  empty_key="x.error_cov.empty")
        self.error_rows.add_button.clicked.connect(self._add_error_covariance)
        card.add(self.error_rows)
        self._error_hint = TKey("x.reason.hint", role="hint")
        card.add(self._error_hint)

    # -- section 3: common method bias --------------------------------- #

    def _build_method_factor(self) -> None:
        card = self.add_card("x.cmb")
        card.add(InfoBanner("x.cmb.explain"))

        self._cmb_enabled = TCheckBox("x.cmb_enable")
        self._cmb_enabled.toggled.connect(self._on_cmb_enabled)
        card.add(self._cmb_enabled)

        self._cmb_loading = ValueSlider(*METHOD_LOADING_RANGE, 0.30)
        self._cmb_loading.value_changed.connect(self._on_cmb_loading)
        self._cmb_loading_field = Field("x.cmb_loading", self._cmb_loading)
        card.add(self._cmb_loading_field)

        self._cmb_all = TCheckBox("x.cmb_all_items")
        self._cmb_all.toggled.connect(self._on_cmb_all)
        card.add(self._cmb_all)
        self._cmb_subset_label = TKey("x.cmb_subset", role="hint")
        card.add(self._cmb_subset_label)

        self._cmb_scroll = QScrollArea()
        self._cmb_scroll.setWidgetResizable(True)
        self._cmb_scroll.setFrameShape(QFrame.Shape.StyledPanel)
        self._cmb_scroll.setMaximumHeight(170)
        self._cmb_host = QWidget()
        self._cmb_layout = QVBoxLayout(self._cmb_host)
        self._cmb_layout.setContentsMargins(8, 6, 8, 6)
        self._cmb_layout.setSpacing(2)
        self._cmb_scroll.setWidget(self._cmb_host)
        # Item names are identifiers; they must not mirror under Arabic.
        theme.keep_ltr(self._cmb_scroll)
        card.add(self._cmb_scroll)
        self._cmb_boxes: List[Tuple[str, QCheckBox]] = []

    # -- the live price tag -------------------------------------------- #

    def _build_summary(self) -> None:
        card = self.add_card("x.summary")
        strip = QHBoxLayout()
        strip.setSpacing(8)
        self._badge_cross = StatBadge("x.cross_loadings")
        self._badge_error = StatBadge("x.error_cov")
        self._badge_method = StatBadge("x.method_loadings")
        self._badge_params = StatBadge("p.free_params")
        self._badge_df = StatBadge("p.df")
        for badge in (self._badge_cross, self._badge_error, self._badge_method,
                      self._badge_params, self._badge_df):
            theme.set_role(badge, "card")
            strip.addWidget(badge)
        strip.addStretch(1)
        card.add(strip)
        card.add(TKey("x.df_cost", role="hint"))

    # ------------------------------------------------------------------ #
    # Lifecycle
    # ------------------------------------------------------------------ #

    def rebuild(self) -> None:
        with self.quiet():
            self._rebuild_cross_rows()
            self._rebuild_error_rows()
            self._rebuild_method_items()
            self._load_policy()
            self._load_method_factor()
            self._update_availability()
        self._update_summary()

    def refresh(self) -> None:
        # Every chooser carries translated labels, and the reason line edit
        # follows the interface language, so a language switch means the rows
        # are rebuilt rather than patched.
        self.rebuild()

    def set_theme(self, name: str) -> None:
        super().set_theme(name)
        self._update_summary()

    # ------------------------------------------------------------------ #
    # Cross-loadings
    # ------------------------------------------------------------------ #

    def _rebuild_cross_rows(self) -> None:
        self.cross_rows.clear()
        for cross in list(self.spec.cross_loadings):
            self.cross_rows.add_row(self._cross_row(cross))

    def _add_cross_loading(self) -> None:
        items = item_choices(self.spec)
        factors = factor_choices(self.spec)
        if not items or len(factors) < 2:
            return
        item_id = items[0][0]
        home = self.spec.home_factor_of(item_id)
        target = next((fid for fid, _label in factors if fid != home),
                      factors[0][0])
        self.spec.cross_loadings.append(
            CrossLoading(item_id=item_id, factor_id=target, loading=0.20))
        self.edit(structural=True)

    def _cross_row(self, cross: CrossLoading) -> Row:
        row = Row()
        item = IdCombo()
        item.set_choices(item_choices(self.spec), keep=cross.item_id)
        item_field = Field("m.item", item, label_width=0)
        row.add(item_field, 4)

        factor = IdCombo()
        factor.set_choices(factor_choices(self.spec), keep=cross.factor_id)
        factor_field = Field("x.on_factor", factor, label_width=0)
        row.add(factor_field, 4)

        slider = ValueSlider(*CROSS_LOADING_RANGE, cross.loading)
        row.add(Field("m.loading", slider, label_width=0), 5)
        row.add_delete_button()

        def check() -> None:
            # A cross-loading onto the item's own home factor says nothing:
            # that loading is already in the measurement model.
            home = self.spec.home_factor_of(cross.item_id)
            if home and cross.factor_id == home:
                factor_field.set_error(translator.t("x.self_loading"))
            else:
                _clear_error(factor_field)

        def on_item(value: str) -> None:
            cross.item_id = value
            check()
            self.edit()

        def on_factor(value: str) -> None:
            cross.factor_id = value
            check()
            self.edit()

        item.value_changed.connect(on_item)
        factor.value_changed.connect(on_factor)
        slider.value_changed.connect(
            lambda value: (setattr(cross, "loading", value), self.edit()))
        row.removed.connect(lambda _r: self._remove_cross_loading(cross))
        check()
        return row

    def _remove_cross_loading(self, cross: CrossLoading) -> None:
        self.spec.cross_loadings = [c for c in self.spec.cross_loadings
                                    if c is not cross]
        self.edit(structural=True)

    # -- the auto policy ------------------------------------------------ #

    def _load_policy(self) -> None:
        policy = self.spec.cross_loading_policy
        self._policy_enabled.setChecked(policy.enabled)
        self._policy_proportion.setValue(policy.proportion_of_items * 100.0)
        low, high = policy.magnitude_range
        # Widen both spins before loading, or the ceiling left over from the
        # previous values would clamp the incoming ones.
        self._magnitude_low.setMaximum(CROSS_LOADING_RANGE[1])
        self._magnitude_high.setMinimum(0.0)
        self._magnitude_high.setValue(float(high))
        self._magnitude_low.setValue(float(low))
        self._apply_magnitude_bounds()
        self._policy_across.setChecked(policy.across_constructs_only)
        self._policy_negative.setChecked(policy.allow_negative)
        self._policy_max.setValue(max(1, policy.max_per_item))
        self._set_policy_enabled(policy.enabled)

    def _set_policy_enabled(self, enabled: bool) -> None:
        for field in self._policy_fields:
            field.setEnabled(enabled)
        for switch in self._policy_switches:
            switch.setEnabled(enabled)

    def _on_policy_enabled(self, checked: bool) -> None:
        self._set_policy_enabled(checked)
        self.spec.cross_loading_policy.enabled = checked
        self.edit()

    def _apply_magnitude_bounds(self) -> None:
        """Keep the two bounds from crossing by clamping their ranges."""
        self._magnitude_low.setMaximum(self._magnitude_high.value())
        self._magnitude_high.setMinimum(self._magnitude_low.value())

    def _on_magnitude(self) -> None:
        if self._updating:
            return
        with self.quiet():
            self._apply_magnitude_bounds()
        low = float(self._magnitude_low.value())
        high = float(self._magnitude_high.value())
        self.spec.cross_loading_policy.magnitude_range = (low, high)
        self.edit()

    def _on_policy(self) -> None:
        if self._updating:
            return
        policy = self.spec.cross_loading_policy
        policy.proportion_of_items = percent_value(self._policy_proportion)
        policy.across_constructs_only = self._policy_across.isChecked()
        policy.allow_negative = self._policy_negative.isChecked()
        policy.max_per_item = int(self._policy_max.value())
        self.edit()

    # ------------------------------------------------------------------ #
    # Error covariances
    # ------------------------------------------------------------------ #

    def _rebuild_error_rows(self) -> None:
        self.error_rows.clear()
        for cov in list(self.spec.error_covariances):
            self.error_rows.add_row(self._error_row(cov))

    def _add_error_covariance(self) -> None:
        items = item_choices(self.spec)
        if len(items) < 2:
            return
        self.spec.error_covariances.append(ErrorCovariance(
            item_a=items[0][0], item_b=items[1][0], correlation=0.20))
        self.edit(structural=True)

    def _error_row(self, cov: ErrorCovariance) -> Row:
        row = Row()
        # Four controls on one line would squeeze the slider out of
        # existence, so the pair and its size go on the first line and the
        # free-text reason gets the width of the row underneath.
        body = QWidget()
        body_lay = QVBoxLayout(body)
        body_lay.setContentsMargins(0, 0, 0, 0)
        body_lay.setSpacing(4)
        top = QHBoxLayout()
        top.setSpacing(8)
        body_lay.addLayout(top)

        choices = item_choices(self.spec)
        first = IdCombo()
        first.set_choices(choices, keep=cov.item_a)
        first_field = Field("x.item_a", first, label_width=0)
        top.addWidget(first_field, 4)
        second = IdCombo()
        second.set_choices(choices, keep=cov.item_b)
        second_field = Field("x.item_b", second, label_width=0)
        top.addWidget(second_field, 4)

        slider = ValueSlider(*ERROR_COV_RANGE, cov.correlation)
        top.addWidget(Field("s.correlation", slider, label_width=0), 5)

        reason = QLineEdit()
        reason.setText(cov.reason.ar if translator.is_rtl else cov.reason.en)
        body_lay.addWidget(Field("x.reason", reason, ltr_editor=False,
                                 label_width=0))
        row.add(body, 1)
        row.add_delete_button()

        def check() -> None:
            # An item cannot covary with itself: that is its own variance.
            same = bool(cov.item_a) and cov.item_a == cov.item_b
            message = translator.t("x.same_item") if same else ""
            if same:
                second_field.set_error(message)
                first_field.set_error(message)
            else:
                _clear_error(second_field)
                _clear_error(first_field)

        def on_first(value: str) -> None:
            cov.item_a = value
            check()
            self.edit()

        def on_second(value: str) -> None:
            cov.item_b = value
            check()
            self.edit()

        def on_reason(text: str) -> None:
            if translator.is_rtl:
                cov.reason.ar = text
            else:
                cov.reason.en = text
            self.edit()

        first.value_changed.connect(on_first)
        second.value_changed.connect(on_second)
        slider.value_changed.connect(
            lambda value: (setattr(cov, "correlation", value), self.edit()))
        reason.textEdited.connect(on_reason)
        row.removed.connect(lambda _r: self._remove_error_covariance(cov))
        check()
        return row

    def _remove_error_covariance(self, cov: ErrorCovariance) -> None:
        self.spec.error_covariances = [c for c in self.spec.error_covariances
                                       if c is not cov]
        self.edit(structural=True)

    # ------------------------------------------------------------------ #
    # Common method bias
    # ------------------------------------------------------------------ #

    def _rebuild_method_items(self) -> None:
        while self._cmb_layout.count():
            entry = self._cmb_layout.takeAt(0)
            widget = entry.widget()
            if widget is not None:
                widget.setParent(None)
                widget.deleteLater()
        self._cmb_boxes = []
        selected = set(self.spec.common_method_bias.item_ids)
        for item_id, label in item_choices(self.spec):
            box = QCheckBox(label)
            box.setChecked(item_id in selected)
            box.toggled.connect(
                lambda _checked, iid=item_id: self._on_cmb_item(iid))
            self._cmb_layout.addWidget(box)
            self._cmb_boxes.append((item_id, box))
        self._cmb_layout.addStretch(1)

    def _load_method_factor(self) -> None:
        cmb = self.spec.common_method_bias
        self._cmb_enabled.setChecked(cmb.enabled)
        self._cmb_loading.set_value(cmb.loading)
        self._cmb_all.setChecked(not cmb.item_ids)
        self._apply_cmb_enabled()

    def _apply_cmb_enabled(self) -> None:
        enabled = self._cmb_enabled.isChecked()
        self._cmb_loading_field.setEnabled(enabled)
        self._cmb_all.setEnabled(enabled)
        self._cmb_subset_label.setEnabled(enabled)
        # "All items" and a hand-picked subset are the same control from two
        # sides, so the list goes dead while "all items" stands.
        self._cmb_scroll.setEnabled(enabled and not self._cmb_all.isChecked())

    def _on_cmb_enabled(self, checked: bool) -> None:
        self.spec.common_method_bias.enabled = checked
        self._apply_cmb_enabled()
        self.edit()

    def _on_cmb_loading(self, value: float) -> None:
        self.spec.common_method_bias.loading = value
        self.edit()

    def _on_cmb_all(self, checked: bool) -> None:
        cmb = self.spec.common_method_bias
        if checked:
            cmb.item_ids = []
        elif not cmb.item_ids:
            # An empty list already means "every item", so leaving the subset
            # empty would say nothing.  Start from everything selected and let
            # the researcher untick.
            cmb.item_ids = [i.id for i in self.spec.all_items()]
        with self.quiet():
            selected = set(cmb.item_ids)
            for item_id, box in self._cmb_boxes:
                box.setChecked(item_id in selected)
        self._apply_cmb_enabled()
        self.edit()

    def _on_cmb_item(self, item_id: str) -> None:
        if self._updating:
            return
        cmb = self.spec.common_method_bias
        chosen = [iid for iid, box in self._cmb_boxes if box.isChecked()]
        cmb.item_ids = chosen
        with self.quiet():
            self._cmb_all.setChecked(not chosen)
        self._apply_cmb_enabled()
        self.edit()

    # ------------------------------------------------------------------ #
    # Availability and the summary strip
    # ------------------------------------------------------------------ #

    def _update_availability(self) -> None:
        items = self.spec.all_items()
        factors = self.spec.all_factor_ids()
        has_items = bool(items)
        self.cross_rows.add_button.setEnabled(has_items and len(factors) >= 2)
        self.error_rows.add_button.setEnabled(len(items) >= 2)
        self._cross_hint.setVisible(not has_items)
        self._error_hint.set_key("x.reason.hint" if len(items) >= 2
                                 else "x.needs_items")

    def _update_summary(self) -> None:
        spec = self.spec
        self._badge_cross.set_value(len(spec.cross_loadings))
        self._badge_error.set_value(len(spec.error_covariances))
        cmb = spec.common_method_bias
        method = (len(cmb.item_ids) or spec.n_items) if cmb.enabled else 0
        self._badge_method.set_value(method)
        try:
            params = spec.count_free_parameters()
            df = spec.degrees_of_freedom()
        except Exception:
            self._badge_params.set_value("-")
            self._badge_df.set_value("-")
            return
        self._badge_params.set_value(params)
        self._badge_df.set_value(df, kind="pass" if df > 0 else "fail")


__all__ = ["ComplexityPage"]
